"use client";

import { useState } from "react";
import type { ArchetypeId, ArchetypeResult, PaymentScenario } from "@/lib/types";
import { ARCHETYPES } from "@/lib/archetypes";

interface DesignBriefProps {
  brief: string;
  scenario: PaymentScenario;
  results: Partial<Record<ArchetypeId, ArchetypeResult>>;
}

export function DesignBrief({ brief, scenario, results }: DesignBriefProps) {
  const [copied, setCopied] = useState(false);

  const resultList = Object.values(results).filter(
    (r): r is ArchetypeResult => r !== undefined && !r.loading
  );

  function buildFullSpec(): string {
    const lines: string[] = [];

    lines.push("=".repeat(64));
    lines.push("TRUST LINE — INTERVENTION BOUNDARY SPECIFICATION");
    lines.push(`Generated: ${new Date().toISOString()}`);
    lines.push("=".repeat(64));
    lines.push("");
    lines.push("SCENARIO");
    lines.push("-".repeat(32));
    lines.push(`Feature:       ${scenario.featureName}`);
    lines.push(`Autonomous:    ${scenario.autonomousAction}`);
    lines.push(`Confirmation:  ${scenario.confirmationAction}`);
    lines.push(`Market:        ${scenario.marketContext}`);
    lines.push("");
    lines.push("TRUST LINE POSITIONS");
    lines.push("-".repeat(32));

    const sorted = resultList.sort((a, b) => b.trustPosition - a.trustPosition);
    for (const result of sorted) {
      const archetype = ARCHETYPES[result.archetypeId];
      const bar = "█".repeat(Math.round(result.trustPosition * 20));
      const empty = "░".repeat(20 - Math.round(result.trustPosition * 20));
      lines.push(
        `${archetype.name.padEnd(26)} ${bar}${empty} ${(result.trustPosition * 100).toFixed(0).padStart(3)}`
      );
    }

    lines.push("");

    for (const result of resultList) {
      const archetype = ARCHETYPES[result.archetypeId];
      lines.push("=".repeat(64));
      lines.push(archetype.name.toUpperCase());
      lines.push(`Trust position: ${(result.trustPosition * 100).toFixed(0)}/100`);
      lines.push("");
      lines.push(`Rationale: ${result.rationale}`);
      lines.push("");
      lines.push("SILENT AUTONOMY — acts without notification when:");
      for (const c of result.interventionBoundary.silentAutonomy) {
        lines.push(`  • ${c}`);
      }
      lines.push("");
      lines.push("NOTIFY AND PROCEED — acts but notifies when:");
      for (const c of result.interventionBoundary.notifyAndProceed) {
        lines.push(`  • ${c}`);
      }
      lines.push("");
      lines.push("CONFIRM BEFORE ACTING — pauses for explicit confirmation when:");
      for (const c of result.interventionBoundary.confirmBeforeActing) {
        lines.push(`  • ${c}`);
      }
      lines.push("");
    }

    if (brief) {
      lines.push("=".repeat(64));
      lines.push("DESIGN BRIEF");
      lines.push("-".repeat(32));
      lines.push(brief);
      lines.push("");
    }

    lines.push("=".repeat(64));
    lines.push("Generated by trust-line · github.com/kgkazakos/trust-line");
    lines.push("Part of the CPR Orbital series · Computational Product Research");
    lines.push("=".repeat(64));

    return lines.join("\n");
  }

  async function handleCopy() {
    try {
      await navigator.clipboard.writeText(buildFullSpec());
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      // fallback: select the textarea
    }
  }

  return (
    <div className="space-y-4">
      <div className="flex items-center justify-between">
        <div>
          <p className="text-xs font-mono text-[var(--text-dim)] uppercase tracking-widest mb-1">
            Design Brief
          </p>
          <h2 className="text-sm font-medium text-[var(--text-secondary)]">
            Engineering handoff spec
          </h2>
        </div>
        <button
          onClick={handleCopy}
          className={`text-xs font-mono px-3 py-1.5 rounded border transition-all duration-200 
            ${copied
              ? "border-[#34A853] text-[#34A853] bg-[#34A853]/10"
              : "border-[var(--border-mid)] text-[var(--text-dim)] hover:border-[var(--blue-google)] hover:text-[var(--blue-google)]"
            }`}
        >
          {copied ? "✓ Copied" : "Copy full spec"}
        </button>
      </div>

      {/* Brief text */}
      {brief && (
        <div className="bg-[var(--surface-1)] border border-[var(--border-dim)] rounded-lg p-5">
          <p className="text-xs font-mono text-[var(--text-secondary)] leading-relaxed whitespace-pre-wrap">
            {brief}
          </p>
        </div>
      )}

      {/* Raw spec preview */}
      <div className="relative">
        <div className="bg-[var(--navy-950)] border border-[var(--border-dim)] rounded-lg overflow-hidden">
          <div className="flex items-center justify-between px-4 py-2.5 border-b border-[var(--border-dim)]">
            <span className="text-xs font-mono text-[var(--text-dim)]">
              Full specification
            </span>
            <div className="flex gap-1.5">
              <div className="w-2.5 h-2.5 rounded-full bg-[var(--border-mid)]" />
              <div className="w-2.5 h-2.5 rounded-full bg-[var(--border-mid)]" />
              <div className="w-2.5 h-2.5 rounded-full bg-[var(--border-mid)]" />
            </div>
          </div>
          <pre className="px-4 py-4 text-xs font-mono text-[var(--text-dim)] overflow-auto max-h-72 leading-relaxed">
            {buildFullSpec()}
          </pre>
        </div>
      </div>

      {/* Attribution */}
      <div className="flex items-center justify-between pt-2">
        <p className="text-xs font-mono text-[var(--text-dim)]">
          trust-line · CPR Orbital Series
        </p>
        <a
          href="https://github.com/kgkazakos/trust-line"
          target="_blank"
          rel="noopener noreferrer"
          className="text-xs font-mono text-[var(--blue-google)] hover:text-[var(--blue-bright)] transition-colors"
        >
          github.com/kgkazakos/trust-line ↗
        </a>
      </div>
    </div>
  );
}
